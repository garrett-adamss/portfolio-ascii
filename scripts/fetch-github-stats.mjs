import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const outputPath = join(root, "src/data/githubStats.generated.ts");

const USERNAME = "garrett-adamss";
const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;

const headers = {
  Accept: "application/vnd.github+json",
  "User-Agent": "portfolio-ascii-stats",
  ...(token ? { Authorization: `Bearer ${token}` } : {}),
};

async function github(url, accept) {
  const response = await fetch(url, {
    headers: accept ? { ...headers, Accept: accept } : headers,
  });

  if (!response.ok) {
    throw new Error(`GitHub API ${response.status} for ${url}`);
  }

  return response.json();
}

async function fetchContributorStats(owner, repo) {
  const url = `https://api.github.com/repos/${owner}/${repo}/stats/contributors`;

  for (let attempt = 0; attempt < 8; attempt++) {
    const response = await fetch(url, { headers });

    if (response.status === 202 || response.status === 403) {
      await sleep(1500 + attempt * 1500);
      continue;
    }

    if (!response.ok) {
      throw new Error(`Contributor stats ${response.status} for ${repo}`);
    }

    return response.json();
  }

  return [];
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function formatCount(value) {
  return value.toLocaleString("en-US");
}

async function fetchLinesOfCode(repos) {
  let additions = 0;
  let deletions = 0;

  for (const repo of repos) {
    if (repo.fork) continue;

    const stats = await fetchContributorStats(USERNAME, repo.name);
    for (const contributor of stats) {
      if (contributor.author?.login !== USERNAME) continue;

      for (const week of contributor.weeks ?? []) {
        additions += week.a ?? 0;
        deletions += week.d ?? 0;
      }
    }

    await sleep(1200);
  }

  return { additions, deletions };
}

async function main() {
  const user = await github(`https://api.github.com/users/${USERNAME}`);
  const repos = await github(
    `https://api.github.com/users/${USERNAME}/repos?per_page=100&type=owner`,
  );

  const stars = repos.reduce(
    (total, repo) => total + (repo.stargazers_count ?? 0),
    0,
  );

  const commits = await github(
    `https://api.github.com/search/commits?q=author:${USERNAME}`,
    "application/vnd.github.cloak-preview+json",
  );

  let additions = 0;
  let deletions = 0;

  try {
    ({ additions, deletions } = await fetchLinesOfCode(repos));
  } catch (error) {
    console.warn(`Could not fetch lines of code: ${error.message}`);
  }

  const stats = [
    { label: "Repos", value: String(user.public_repos) },
    { label: "Commits", value: formatCount(commits.total_count ?? 0) },
    {
      label: "LOC",
      value: "",
      html: true,
      additions: `${formatCount(additions)}++`,
      deletions: `${formatCount(deletions)}--`,
    },
    { label: "Stars", value: String(stars) },
    { label: "Followers", value: String(user.followers) },
  ];

  const contents = `// Generated by scripts/fetch-github-stats.mjs — do not edit by hand.
// Re-run: npm run fetch:github-stats

export const githubStats = ${JSON.stringify(stats, null, 2)} as const;
`;

  writeFileSync(outputPath, contents, "utf8");

  console.log("GitHub stats written to src/data/githubStats.generated.ts");
  for (const stat of stats) {
    if (stat.html) {
      console.log(`  ${stat.label}: ${stat.additions} ${stat.deletions}`);
    } else {
      console.log(`  ${stat.label}: ${stat.value}`);
    }
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
